#!/usr/bin/env node
// gen-clients.mjs [--check] — everything derived from the plugin's version, its skills and the servers table in lib.mjs,
// written in one go so no copy can drift:
//   · plugins/cloudbackend/.mcp.json: the three servers (docs and build run inside the plugin, deploy is CloudBackend's
//     per-tenant server, its tenant from plugin.json's userConfig)
//   · the marketplace entry's description, homepage, licence and keywords, copied from plugin.json
//   · clients/cursor/mcp.json, clients/vscode/{mcp.json,ADD-MCP.md}, clients/codex/config.toml, clients/gemini/settings.json,
//     clients/README.md: the two local servers in each client's shape, with <plugin-dir> standing for the unzipped plugin
//   · the plugin README's install block and skills table, between <!-- install:start/end --> and <!-- skills:start/end -->
//   · the hub's public/plugin.json, which the portal's Tools page and the launch page render
//   · dist/marketplace.json, the marketplace the portal serves (an archive source with an absolute https URL; a
//     marketplace added by URL cannot resolve a relative source; pack.mjs fills the sha256), and dist/index.json
// The plugin's base URL is the portal's address (the hub's public/portal.json) + /plugin; the GitHub form is
// plugin.json's `repository` or lib.mjs's placeholder until Robin names the repository.
// --check writes nothing and exits 1 if a tracked output (everything but dist/) would change.
import {existsSync, readFileSync} from 'node:fs';
import path from 'node:path';
import {ROOT, PLUGIN_DIR, PLUGIN_NAME, MARKETPLACE_NAME, HUB, DIST, HOST, SERVERS, DEPLOY_URL_FORM, TENANT_CONFIG_KEY, TENANT_PATTERN,
        GITHUB_BRANCH_TESTERS, GITHUB_BRANCH_WORK, MANIFEST, MARKETPLACE, marketplaceUrl, indexUrl, zipUrl, zipName, githubRepo,
        readJson, writeText, isoDate, fail} from './lib.mjs';

const check = process.argv.includes('--check');
const manifest = readJson(MANIFEST);
const marketplace = readJson(MARKETPLACE);
const version = manifest.version;
if (!manifest.userConfig || !manifest.userConfig[TENANT_CONFIG_KEY]) fail(`plugin.json has no userConfig.${TENANT_CONFIG_KEY}: the deploy connector's tenant comes from it`);
const provenanceFile = path.join(PLUGIN_DIR, 'SKILLS.json');
const provenance = existsSync(provenanceFile) ? readJson(provenanceFile) : {generated: null, skills: []};
const descriptions = new Map();                            // skill name → its frontmatter description
for (const s of provenance.skills) {
  const skillMd = path.join(PLUGIN_DIR, 'skills', s.name, 'SKILL.md');
  if (!existsSync(skillMd)) continue;
  const m = /^description:\s*"?(.*?)"?\s*$/m.exec(readFileSync(skillMd, 'utf8').split('\n---')[0] || '');
  if (m) descriptions.set(s.name, m[1].replace(/\\"/g, '"'));
}
const [docs, build, deploy] = ['docs', 'build', 'deploy'].map(k => SERVERS.find(s => s.key === k));
const github = githubRepo();
const MARKET_URL = marketplaceUrl(), INDEX_URL = indexUrl(), ZIP_URL = zipUrl(version), ZIP = zipName(version);
const json = o => JSON.stringify(o, null, 2) + '\n';
const stamp = `Generated by scripts/gen-clients.mjs for plugin version ${version}; edit the generator, not this file.`;
const outputs = new Map();                                  // path (relative to ROOT, or absolute) → text

// ---- the plugin's .mcp.json (plan 2026-11-04, part B) ----------------------------------------------------------------
// The build server runs through its launcher script rather than `${CLAUDE_PLUGIN_DATA}/venv/bin/python` as a command:
// Claude Code expands ${CLAUDE_PLUGIN_DATA} in args and env, not in command (measured on 2.1.316, 2026-11-04; a
// command under the data directory failed even once the file existed). The launcher gets the data directory as its
// argument and execs that python.
outputs.set(path.join(PLUGIN_DIR, '.mcp.json'), json({mcpServers: {
  [docs.name]: {command: 'node', args: [`\${CLAUDE_PLUGIN_ROOT}/${docs.entry}`]},
  [build.name]: {command: 'sh', args: [`\${CLAUDE_PLUGIN_ROOT}/${build.launcher}`, '${CLAUDE_PLUGIN_DATA}'], env: {PYTHONPATH: `\${CLAUDE_PLUGIN_ROOT}/${build.src}`}},
  [deploy.name]: {type: 'http', url: `${HOST}/mcp/\${user_config.${TENANT_CONFIG_KEY}}`},
}}));

// ---- the marketplace entry follows plugin.json ---------------------------------------------------------------------
{
  const m = structuredClone(marketplace);
  const entry = m.plugins.find(p => p.name === PLUGIN_NAME);
  if (!entry) fail(`no "${PLUGIN_NAME}" entry in the marketplace`);
  for (const k of ['description', 'homepage', 'license', 'keywords']) if (manifest[k] !== undefined) entry[k] = manifest[k];
  if (manifest.author) entry.author = manifest.author;
  outputs.set(MARKETPLACE, json(m));
}

// ---- clients/: the two local servers for other MCP clients --------------------------------------------------------------
// <plugin-dir> is the unzipped plugin; the build server's environment is made by its own hook script, run once by hand.
const P = '<plugin-dir>';
const local = {
  docs: {command: 'node', args: [`${P}/${docs.entry}`]},
  build: {command: `${P}/.data/venv/bin/python`, args: ['-m', build.module], env: {PYTHONPATH: `${P}/${build.src}`}},
};
const venvLine = `sh ${P}/scripts/ensure-build-venv.sh ${P}/.data`;
outputs.set('clients/cursor/mcp.json', json({mcpServers: {[docs.name]: local.docs, [build.name]: local.build}}));
outputs.set('clients/vscode/mcp.json', json({servers: {[docs.name]: {type: 'stdio', ...local.docs}, [build.name]: {type: 'stdio', ...local.build}}}));
outputs.set('clients/vscode/ADD-MCP.md', `# VS Code: add the servers

${stamp}

Unzip the plugin, run \`${venvLine}\` once (the build server's Python environment; needs Python 3.12 or uv), then one
command per server with \`${P}\` replaced by the unzipped folder (user settings; Copilot agent mode lists the tools):

\`\`\`bash
code --add-mcp '${JSON.stringify({name: docs.name, ...local.docs})}'
code --add-mcp '${JSON.stringify({name: build.name, ...local.build})}'
\`\`\`

Or copy \`mcp.json\` next to this file to the workspace's \`.vscode/mcp.json\` and replace \`${P}\` there.
`);
outputs.set('clients/codex/config.toml', `# Codex CLI: append to ~/.codex/config.toml, with ${P} replaced by the unzipped plugin
# ${stamp}

[mcp_servers.${docs.name}]
command = "${local.docs.command}"
args = ${JSON.stringify(local.docs.args)}

[mcp_servers.${build.name}]
command = "${local.build.command}"
args = ${JSON.stringify(local.build.args)}
env = { PYTHONPATH = "${local.build.env.PYTHONPATH}" }
`);
outputs.set('clients/gemini/settings.json', json({mcpServers: {[docs.name]: local.docs, [build.name]: local.build}}));
outputs.set('clients/README.md', `# The plugin's servers for other clients

${stamp}

The documentation and build servers run on your computer, from the unzipped plugin (\`${ZIP}\` from the marketplace,
or a checkout of this repository: \`plugins/cloudbackend/\`). Every file here names that folder as \`${P}\`; replace it.
Once: \`${venvLine}\` makes the build server's Python environment (Python 3.12 or uv). The documentation server
needs Node 22 and nothing else; it reads the developer portal and needs no sign-in.

| Client | File | How |
| --- | --- | --- |
| Cursor | \`cursor/mcp.json\` | as \`.cursor/mcp.json\` in the project, or merged into \`~/.cursor/mcp.json\` |
| VS Code | \`vscode/mcp.json\`, \`vscode/ADD-MCP.md\` | \`code --add-mcp\` one-liners, or the file as \`.vscode/mcp.json\` |
| Codex CLI | \`codex/config.toml\` | append to \`~/.codex/config.toml\` |
| Gemini CLI | \`gemini/settings.json\` | merge into \`~/.gemini/settings.json\` |

| Server | Runs | Gives |
| --- | --- | --- |
| \`${docs.name}\` | \`node ${P}/${docs.entry}\` | ${docs.what} |
| \`${build.name}\` | \`${P}/.data/venv/bin/python -m ${build.module}\` with \`PYTHONPATH=${P}/${build.src}\` | ${build.what} |

The deploy connector is CloudBackend's and per tenant (\`${DEPLOY_URL_FORM}\`): \`${P}/scripts/connect-deploy.sh <tenant> --print\`
prints it in each client's shape. The skills themselves are Claude's; for another agent, point it at
\`${P}/skills/<name>/SKILL.md\` (the open Agent Skills layout).
`);

// ---- the plugin README ------------------------------------------------------------------------------------------
const installGithub = [`claude plugin marketplace add ${github}`, `claude plugin install ${PLUGIN_NAME}@${MARKETPLACE_NAME}`];
const installUrl = [`claude plugin marketplace add ${MARKET_URL}`, `claude plugin install ${PLUGIN_NAME}@${MARKETPLACE_NAME}`];
const installSession = `claude --plugin-url ${ZIP_URL}`;
const update = [`claude plugin marketplace update ${MARKETPLACE_NAME}`, `claude plugin update ${PLUGIN_NAME}@${MARKETPLACE_NAME}`];
const installBlock = `<!-- install:start -->
## Install

Version ${version} · the plugin \`${PLUGIN_NAME}@${MARKETPLACE_NAME}\`

**Claude Code, from GitHub** (the testers' path; the repository is private, so Claude Code needs a GitHub credential it
can use without prompting: an SSH key loaded in \`ssh-agent\`, or \`gh auth login\` + \`gh auth setup-git\` with
\`CLAUDE_CODE_PLUGIN_PREFER_HTTPS=1\` set in your shell):

\`\`\`bash
${installGithub.join('\n')}
\`\`\`

The install asks once for your CloudBackend tenant (lowercase letters and digits, the name in your console address);
that fills the deploy connector, \`${deploy.name}\` at \`${DEPLOY_URL_FORM}\`, which signs you in at your tenant on
first use. \`${GITHUB_BRANCH_TESTERS}\` is what testers get; work happens on \`${GITHUB_BRANCH_WORK}\`.

**Claude Code, without GitHub access:** the same marketplace, served by the developer portal:

\`\`\`bash
${installUrl.join('\n')}
\`\`\`

**One session, nothing installed:** \`${installSession}\`

**Updates:** \`${update[0]}\`, then \`${update[1]}\` (a marketplace you added yourself does not update by itself;
\`/plugin\` → Marketplaces can switch auto-update on).

**The build server needs Python 3.12 or \`uv\`.** A session-start hook creates its environment once; the first session may
show \`${build.name}\` as disconnected until the hook finishes (one line on the terminal says what it did). Without
Python 3.12 or \`uv\` the hook says so, and the workflow skill runs those steps as checklists.

**claude.ai, Claude Desktop, Cowork:** the skills are uploaded from the developer portal's Tools page, the documentation
server is the Claude Desktop extension offered there, and the deploy connector is added by hand as a custom connector
(\`scripts/connect-deploy.sh <tenant> --print\` prints the URL; Cowork reads \`.mcp.json\` but cannot fill the tenant).

**Cursor, VS Code, Codex CLI, Gemini CLI:** unzip the plugin and use \`clients/\` (each file names \`${P}\`; the
build server's environment is one \`sh ${P}/scripts/ensure-build-venv.sh ${P}/.data\`).
<!-- install:end -->`;
const skillsBlock = `<!-- skills:start -->
${provenance.skills.length} skills, built from the documentation on ${provenance.generated ?? 'n/a'} (\`SKILLS.json\` has the hashes):

| Skill | Version | Use it when |
| --- | --- | --- |
${provenance.skills.map(s => `| \`${s.name}\` | ${s.version} | ${(descriptions.get(s.name) || '').split(/(?<=\.)\s+Use (?:this|it)\b/)[0].replace(/\|/g, '\\|')} |`).join('\n')}
<!-- skills:end -->`;
const serversBlock = `<!-- servers:start -->
| Server | Runs | Gives |
| --- | --- | --- |
| \`${docs.name}\` | inside the plugin (Node 22; \`servers/docs/\`) | ${docs.what} |
| \`${build.name}\` | inside the plugin (Python ${build.python}; \`servers/build/\` through \`${build.launcher}\`, environment made by \`hooks/hooks.json\`) | ${build.what} |
| \`${deploy.name}\` | CloudBackend's live server, \`${DEPLOY_URL_FORM}\` | ${deploy.what} |
<!-- servers:end -->`;
const readmeFile = path.join(PLUGIN_DIR, 'README.md');
let readme = readFileSync(readmeFile, 'utf8');
for (const [marker, block] of [['install', installBlock], ['skills', skillsBlock], ['servers', serversBlock]]) {
  const re = new RegExp(`<!-- ${marker}:start -->[\\s\\S]*?<!-- ${marker}:end -->`);
  if (!re.test(readme)) fail(`README.md: no <!-- ${marker}:start --> … <!-- ${marker}:end --> markers`);
  readme = readme.replace(re, () => block);
}
outputs.set(readmeFile, readme);

// ---- the hub's public/plugin.json ---------------------------------------------------------------------------------
const skillsOut = provenance.skills.map(s => ({name: s.name, version: s.version, content_hash: s.content_hash}));
const serversOut = {
  docs: {name: docs.name, kind: docs.kind, runtime: docs.runtime, tools: docs.tools, what: docs.what},
  build: {name: build.name, kind: build.kind, runtime: build.runtime, python: build.python, tools: build.tools, what: build.what},
  deploy: {name: deploy.name, kind: deploy.kind, url_form: deploy.url_form, what: deploy.what},
};
const installOut = {
  claude_code_github: installGithub,
  claude_code_url: installUrl,
  claude_code_session: installSession,
  claude_code_update: update,
  claude_ai: 'Upload the skills from the Tools page; the documentation server is the Claude Desktop extension there; add the deploy connector by hand as a custom connector.',
  python_note: `The build server needs Python ${build.python} or uv; a session-start hook makes its environment once, and the first session may show it disconnected until the hook finishes.`,
};
outputs.set(path.join(HUB, 'public', 'plugin.json'), json({
  _comment: [stamp, 'What the portal\'s Tools page and the launch page show about the plugin: one source for the version, the install commands and the servers.'],
  name: PLUGIN_NAME,
  version,
  marketplace: MARKETPLACE_NAME,
  github,
  github_branches: {testers: GITHUB_BRANCH_TESTERS, work: GITHUB_BRANCH_WORK},
  marketplace_url: MARKET_URL,
  index_url: INDEX_URL,
  zip_url: ZIP_URL,
  zip_file: ZIP,
  install: installOut,
  servers: serversOut,
  tenant_config: {key: TENANT_CONFIG_KEY, pattern: TENANT_PATTERN},
  skills_generated: provenance.generated,
  skills: skillsOut,
}));

// ---- dist/: the marketplace the portal serves and the update index (per release; ignored by git, never --check'ed) --------
const hosted = structuredClone(JSON.parse(outputs.get(MARKETPLACE)));
hosted.plugins = hosted.plugins.map(p => p.name !== PLUGIN_NAME ? p : {...p, version, source: {source: 'archive', url: ZIP_URL}});
if (hosted.metadata) hosted.metadata.version = version;
const distOutputs = new Map([
  [path.join(DIST, 'marketplace.json'), json(hosted)],
  [path.join(DIST, 'index.json'), json({
    _comment: [stamp, 'The update index: skills[].version is what a skill\'s footer compares its own version with; file is the download.'],
    name: PLUGIN_NAME, version, generated: isoDate(), github, marketplace_url: MARKET_URL, zip_url: ZIP_URL, zip_file: ZIP,
    install: installOut,
    servers: serversOut,
    skills_generated: provenance.generated,
    skills: skillsOut.map(s => ({...s, file: ZIP_URL})),
  })],
]);

// ---- write or compare --------------------------------------------------------------------------------------------
const resolve = p => path.isAbsolute(p) ? p : path.join(ROOT, p);
const label = p => path.isAbsolute(p) && !p.startsWith(ROOT) ? `hub ${path.relative(HUB, p)}` : path.relative(ROOT, resolve(p));
const changes = [];
for (const [p, text] of outputs) {
  const file = resolve(p);
  const before = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (before === text) continue;
  changes.push(`${before === null ? 'new' : 'changed'}: ${label(p)}`);
  if (!check) writeText(file, text);
}
if (check) {
  if (changes.length) fail(`gen-clients: ${changes.length} output(s) would change:\n  ${changes.join('\n  ')}\nrun: node scripts/gen-clients.mjs`);
  console.log(`.mcp.json, clients, README blocks and the hub's plugin.json are current (version ${version}, ${provenance.skills.length} skills, github ${github})`);
  process.exit(0);
}
for (const [file, text] of distOutputs) writeText(file, text);
console.log(`version ${version}, ${provenance.skills.length} skills, github ${github}: ${outputs.size} outputs (${changes.length} changed) + dist/marketplace.json, dist/index.json`);
for (const c of changes) console.log(`  ${c}`);
