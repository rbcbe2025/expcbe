#!/usr/bin/env node
// gen-clients.mjs [--check] — everything derived from the plugin's version, its skills and the connector URLs, written
// in one go so no copy can drift:
//   · clients/cursor (mcp.json, DEEPLINK.md), clients/vscode (mcp.json, ADD-MCP.md), clients/codex/config.toml,
//     clients/gemini/settings.json, clients/README.md
//   · the plugin README's install block and skills table, between <!-- install:start/end --> and <!-- skills:start/end -->
//   · dist/marketplace.json: the HOSTED marketplace, whose plugin entry is an archive source pointing at the zip URL
//     (a marketplace added by URL cannot resolve a relative source), and dist/index.json, the update index
//   · the hub's public/plugin.json, which the portal's Tools page renders
// --check writes nothing and exits 1 if a tracked output (everything but dist/) would change.
import {existsSync, readFileSync} from 'node:fs';
import path from 'node:path';
import {ROOT, PLUGIN_DIR, PLUGIN_NAME, MARKETPLACE_NAME, HUB, DIST, CONNECTORS, DEPLOY_URL_FORM, MARKETPLACE_URL, INDEX_URL,
        MANIFEST, MARKETPLACE, zipUrl, readJson, writeText, isoDate, fail} from './lib.mjs';

const check = process.argv.includes('--check');
const manifest = readJson(MANIFEST);
const marketplace = readJson(MARKETPLACE);
const version = manifest.version;
const provenanceFile = path.join(PLUGIN_DIR, 'SKILLS.json');
const provenance = existsSync(provenanceFile) ? readJson(provenanceFile) : {generated: null, skills: []};
const descriptions = new Map();                            // skill name → its frontmatter description
for (const s of provenance.skills) {
  const skillMd = path.join(PLUGIN_DIR, 'skills', s.name, 'SKILL.md');
  if (!existsSync(skillMd)) continue;
  const m = /^description:\s*"?(.*?)"?\s*$/m.exec(readFileSync(skillMd, 'utf8').split('\n---')[0] || '');
  if (m) descriptions.set(s.name, m[1].replace(/\\"/g, '"'));
}

const b64 = o => Buffer.from(JSON.stringify(o)).toString('base64');
const deeplink = c => `cursor://anysphere.cursor-deeplink/mcp/install?name=${c.name}&config=${b64({url: c.url})}`;
const vscodeAdd = c => `code --add-mcp '${JSON.stringify({name: c.name, type: 'http', url: c.url})}'`;
const codexToml = CONNECTORS.map(c => `[mcp_servers.${c.name}]\nurl = "${c.url}"\n`).join('\n');
const json = o => JSON.stringify(o, null, 2) + '\n';
const installClaudeCode = [`claude plugin marketplace add ${MARKETPLACE_URL}`, `claude plugin install ${PLUGIN_NAME}@${MARKETPLACE_NAME}`];
const updateClaudeCode = `claude plugin update ${PLUGIN_NAME}@${MARKETPLACE_NAME}`;
const sessionClaudeCode = `claude --plugin-dir ${zipUrl(version).split('/').pop()}`;
const stamp = `Generated by scripts/gen-clients.mjs for plugin version ${version}; edit the generator, not this file.`;

const outputs = new Map();                                  // path (relative to ROOT, or absolute) → text

// ---- clients/ --------------------------------------------------------------------------------------------------
outputs.set('clients/cursor/mcp.json', json({mcpServers: Object.fromEntries(CONNECTORS.map(c => [c.name, {url: c.url}]))}));
outputs.set('clients/cursor/DEEPLINK.md', `# Cursor: install links

${stamp}

One click each; Cursor shows the server and asks before adding it. No sign-in.

${CONNECTORS.map(c => `- **${c.name}** (${c.what}):\n  \`${deeplink(c)}\``).join('\n')}

Or copy \`mcp.json\` next to this file into the project's \`.cursor/mcp.json\` (or merge it into \`~/.cursor/mcp.json\`).

The deploy connector is per tenant: \`plugins/cloudbackend/scripts/connect-deploy.sh <tenant> --print\` prints its link.
`);
outputs.set('clients/vscode/mcp.json', json({servers: Object.fromEntries(CONNECTORS.map(c => [c.name, {type: 'http', url: c.url}]))}));
outputs.set('clients/vscode/ADD-MCP.md', `# VS Code: add the connectors

${stamp}

One command per connector (user settings; Copilot agent mode lists the tools):

\`\`\`bash
${CONNECTORS.map(vscodeAdd).join('\n')}
\`\`\`

Or copy \`mcp.json\` next to this file to the workspace's \`.vscode/mcp.json\`.
`);
outputs.set('clients/codex/config.toml', `# Codex CLI: append to ~/.codex/config.toml
# ${stamp}

${codexToml}`);
outputs.set('clients/gemini/settings.json', json({mcpServers: Object.fromEntries(CONNECTORS.map(c => [c.name, {httpUrl: c.url}]))}));
outputs.set('clients/README.md', `# Connector configs for other clients

${stamp}

The two hosted connectors, read-only and without sign-in, in each client's own shape:

| Client | File | How |
| --- | --- | --- |
| Cursor | \`cursor/mcp.json\`, \`cursor/DEEPLINK.md\` | the deeplinks, or the file as \`.cursor/mcp.json\` |
| VS Code | \`vscode/mcp.json\`, \`vscode/ADD-MCP.md\` | \`code --add-mcp\` one-liners, or the file as \`.vscode/mcp.json\` |
| Codex CLI | \`codex/config.toml\` | append to \`~/.codex/config.toml\` |
| Gemini CLI | \`gemini/settings.json\` | merge into \`~/.gemini/settings.json\` |

| Connector | URL |
| --- | --- |
${CONNECTORS.map(c => `| \`${c.name}\` | \`${c.url}\` |`).join('\n')}

The deploy connector is per tenant (\`${DEPLOY_URL_FORM}\`): \`plugins/cloudbackend/scripts/connect-deploy.sh <tenant>\`.
The skills themselves are Claude's; for another agent, unzip the plugin and point it at \`skills/<name>/SKILL.md\`
(the open Agent Skills layout).
`);

// ---- the plugin README ------------------------------------------------------------------------------------------
const installBlock = `<!-- install:start -->
## Install

Version ${version} · marketplace \`${MARKETPLACE_URL}\`

**Claude Code**

\`\`\`bash
${installClaudeCode.join('\n')}
\`\`\`

Later versions: \`${updateClaudeCode}\` (a marketplace added by URL does not update by itself). For one session
without installing, download the zip from the marketplace and run \`${sessionClaudeCode}\`.

**claude.ai, Claude Desktop, Cowork:** add each connector as a custom connector by URL (Settings → Connectors; no sign-in):
${CONNECTORS.map(c => `\`${c.url}\` (${c.name})`).join(' and ')}. The skills are uploaded from the developer portal's Tools page
until the plugin is listed there.

**Cursor:** one click per connector, ${CONNECTORS.map(c => `[${c.name}](${deeplink(c)})`).join(' and ')}, or
\`clients/cursor/mcp.json\` as \`.cursor/mcp.json\`.

**VS Code:** \`${vscodeAdd(CONNECTORS[0])}\` (and the same for ${CONNECTORS.slice(1).map(c => c.name).join(', ')}), or
\`clients/vscode/mcp.json\` as \`.vscode/mcp.json\`.

**Codex CLI:** append \`clients/codex/config.toml\` to \`~/.codex/config.toml\`. **Gemini CLI:** merge
\`clients/gemini/settings.json\` into \`~/.gemini/settings.json\`.

**Deploying** needs the per-tenant connector, \`${DEPLOY_URL_FORM}\`: \`scripts/connect-deploy.sh <tenant>\`.
<!-- install:end -->`;
const skillsBlock = `<!-- skills:start -->
${provenance.skills.length} skills, built from the documentation on ${provenance.generated ?? 'n/a'} (\`SKILLS.json\` has the hashes):

| Skill | Version | Use it when |
| --- | --- | --- |
${provenance.skills.map(s => `| \`${s.name}\` | ${s.version} | ${(descriptions.get(s.name) || '').split(/(?<=\.)\s+Use (?:this|it)\b/)[0].replace(/\|/g, '\\|')} |`).join('\n')}
<!-- skills:end -->`;
const readmeFile = path.join(PLUGIN_DIR, 'README.md');
let readme = readFileSync(readmeFile, 'utf8');
for (const [marker, block] of [['install', installBlock], ['skills', skillsBlock]]) {
  const re = new RegExp(`<!-- ${marker}:start -->[\\s\\S]*?<!-- ${marker}:end -->`);
  if (!re.test(readme)) fail(`README.md: no <!-- ${marker}:start --> … <!-- ${marker}:end --> markers`);
  readme = readme.replace(re, () => block);
}
outputs.set(readmeFile, readme);

// ---- the hub's public/plugin.json ---------------------------------------------------------------------------------
const skillsOut = provenance.skills.map(s => ({name: s.name, version: s.version, content_hash: s.content_hash}));
outputs.set(path.join(HUB, 'public', 'plugin.json'), json({
  _comment: [stamp, 'What the portal\'s Tools page shows about the plugin: one source for the version, the install commands and the connector URLs.'],
  name: PLUGIN_NAME,
  version,
  marketplace: MARKETPLACE_NAME,
  marketplace_url: MARKETPLACE_URL,
  index_url: INDEX_URL,
  zip_url: zipUrl(version),
  install: {
    claude_code: installClaudeCode,
    claude_code_update: updateClaudeCode,
    claude_code_session: sessionClaudeCode,
    claude_ai: 'Add each connector URL as a custom connector (no sign-in); upload the skills from the Tools page.',
  },
  connectors: {
    docs: CONNECTORS[0].url,
    build: CONNECTORS[1].url,
    deploy_url_form: DEPLOY_URL_FORM,
  },
  cursor_deeplink: Object.fromEntries(CONNECTORS.map(c => [c.key, deeplink(c)])),
  vscode_add_mcp: Object.fromEntries(CONNECTORS.map(c => [c.key, vscodeAdd(c)])),
  codex_toml: codexToml,
  gemini_settings: {mcpServers: Object.fromEntries(CONNECTORS.map(c => [c.name, {httpUrl: c.url}]))},
  skills_generated: provenance.generated,
  skills: skillsOut,
}));

// ---- dist/: the hosted marketplace and the update index (per release; ignored by git, never --check'ed) --------------
const hosted = structuredClone(marketplace);
hosted.plugins = hosted.plugins.map(p => p.name !== PLUGIN_NAME ? p : {...p, version, source: {source: 'archive', url: zipUrl(version)}});
if (hosted.metadata) hosted.metadata.version = version;
const distOutputs = new Map([
  [path.join(DIST, 'marketplace.json'), json(hosted)],
  [path.join(DIST, 'index.json'), json({
    _comment: [stamp, 'The update index: skills[].version is what a skill\'s footer compares its own version with; file is the download.'],
    name: PLUGIN_NAME, version, generated: isoDate(), marketplace_url: MARKETPLACE_URL, zip_url: zipUrl(version),
    install: {claude_code: installClaudeCode, claude_code_update: updateClaudeCode},
    connectors: {docs: CONNECTORS[0].url, build: CONNECTORS[1].url, deploy_url_form: DEPLOY_URL_FORM},
    skills_generated: provenance.generated,
    skills: skillsOut.map(s => ({...s, file: zipUrl(version)})),
  })],
]);

// ---- write or compare --------------------------------------------------------------------------------------------
const resolve = p => path.isAbsolute(p) ? p : path.join(ROOT, p);
const label = p => path.isAbsolute(p) && !p.startsWith(ROOT) ? `hub ${path.relative(HUB, p)}` : path.relative(ROOT, resolve(p));
const changes = [];
for (const [p, text] of outputs) {
  const file = resolve(p);
  const before = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (before === text) continue;
  changes.push(`${before === null ? 'new' : 'changed'}: ${label(p)}`);
  if (!check) writeText(file, text);
}
if (check) {
  if (changes.length) fail(`gen-clients: ${changes.length} output(s) would change:\n  ${changes.join('\n  ')}\nrun: node scripts/gen-clients.mjs`);
  console.log(`clients, README blocks and the hub's plugin.json are current (version ${version}, ${provenance.skills.length} skills)`);
  process.exit(0);
}
for (const [file, text] of distOutputs) writeText(file, text);
console.log(`version ${version}, ${provenance.skills.length} skills: ${outputs.size} outputs (${changes.length} changed) + dist/marketplace.json, dist/index.json`);
for (const c of changes) console.log(`  ${c}`);
